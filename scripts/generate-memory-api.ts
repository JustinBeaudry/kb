#!/usr/bin/env bun
/**
 * Generates src/generated/memory-api.ts from the F1 OpenAPI contract
 * (server/api/openapi.yaml, stored as JSON). Deterministic and dependency-free;
 * tests/remote-envelope.test.ts fails when the committed output drifts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Schema = {
  $ref?: string;
  type?: string;
  enum?: string[];
  items?: Schema;
  properties?: Record<string, Schema>;
  required?: string[];
  additionalProperties?: boolean | Schema;
  description?: string;
};
type Parameter = { name: string; in: string; required?: boolean; schema: Schema };
type Operation = { operationId: string; parameters?: Parameter[] };
type Spec = {
  info: { title: string; version: string };
  paths: Record<string, Record<string, Operation>>;
  components: { schemas: Record<string, Schema> };
};

const pascal = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const comment = (text: string | undefined, indent: string) =>
  text ? `${indent}/** ${text.replaceAll("*/", "* /")} */\n` : "";

function typeOf(s: Schema, indent: string): string {
  if (s.$ref) return s.$ref.replace("#/components/schemas/", "");
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  switch (s.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `${wrap(typeOf(s.items ?? {}, indent))}[]`;
    case "object":
      return objectOf(s, indent);
  }
  return "unknown";
}
const wrap = (t: string) => (t.includes("|") ? `(${t})` : t);
function objectOf(s: Schema, indent: string): string {
  const props = Object.entries(s.properties ?? {});
  const extra =
    typeof s.additionalProperties === "object"
      ? typeOf(s.additionalProperties, indent + "  ")
      : undefined;
  if (props.length === 0)
    return extra ? `Record<string, ${extra}>` : "Record<string, never>";
  const required = new Set(s.required ?? []);
  const lines = props.map(
    ([name, p]) =>
      comment(p.description, indent + "  ") +
      `${indent}  ${name}${required.has(name) ? "" : "?"}: ${typeOf(p, indent + "  ")};`,
  );
  return `{\n${lines.join("\n")}\n${indent}}`;
}

export function generate(spec: Spec): string {
  const out = [
    "// Code generated by scripts/generate-memory-api.ts from server/api/openapi.yaml. DO NOT EDIT.",
    `// ${spec.info.title} ${spec.info.version}. Wire types stay inside src/gateways/memory.gateway.ts.`,
    "",
  ];
  for (const [name, schema] of Object.entries(spec.components.schemas)) {
    out.push(comment(schema.description, "") + `export type ${name} = ${typeOf(schema, "")};`, "");
  }
  const operations: string[] = [];
  for (const [path, methods] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(methods)) {
      operations.push(
        `  ${op.operationId}: { method: ${JSON.stringify(method.toUpperCase())}, path: ${JSON.stringify(path)} },`,
      );
      const query = (op.parameters ?? []).filter((p) => p.in === "query");
      if (query.length > 0) {
        const props: Record<string, Schema> = {};
        for (const p of query) props[p.name] = p.schema;
        const required = query.filter((p) => p.required).map((p) => p.name);
        out.push(
          `export type ${pascal(op.operationId)}Query = ${typeOf({ type: "object", properties: props, required }, "")};`,
          "",
        );
      }
    }
  }
  out.push("export const operations = {", ...operations, "} as const;", "");
  return out.join("\n");
}

export const SPEC_PATH = join(import.meta.dir, "..", "server", "api", "openapi.yaml");
export const OUTPUT_PATH = join(import.meta.dir, "..", "src", "generated", "memory-api.ts");

if (import.meta.main) {
  // SAFETY: the F1 contract is JSON-formatted OpenAPI 3.0; generate() reads only the fields typed above.
  const spec = JSON.parse(readFileSync(SPEC_PATH, "utf8")) as Spec;
  writeFileSync(OUTPUT_PATH, generate(spec));
}
