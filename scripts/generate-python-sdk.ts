#!/usr/bin/env bun
/**
 * Generates sdk/python/kb_client/_generated.py, the typed Python client, from
 * server/api/openapi.yaml (stored as JSON). Deterministic and
 * dependency-free; tests/sdk.test.ts fails when the committed output drifts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { SPEC_PATH } from "./generate-memory-api";

type Schema = {
  $ref?: string;
  type?: string;
  enum?: string[];
  items?: Schema;
  properties?: Record<string, Schema>;
  required?: string[];
  additionalProperties?: boolean | Schema;
  description?: string;
};
type Parameter = { name: string; in: string; required?: boolean; schema: Schema };
type Operation = {
  operationId: string;
  parameters?: Parameter[];
  requestBody?: { content?: { "application/json"?: { schema?: Schema } } };
  responses: Record<string, { content?: { "application/json"?: { schema?: Schema } } }>;
};
type Spec = {
  info: { title: string; version: string };
  paths: Record<string, Record<string, Operation>>;
  components: { schemas: Record<string, Schema> };
};

const pascal = (s: string) => s.replace(/(^|_)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());
const snake = (s: string) => s.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase());
const refName = (s: Schema | undefined) => s?.$ref?.replace("#/components/schemas/", "");
const py = (v: string) => JSON.stringify(v);
const docLine = (text: string | undefined) => (text ? `# ${text.replace(/\s+/g, " ").trim()}\n` : "");

export function generatePython(spec: Spec): string {
  const blocks: string[] = [];
  function typeOf(s: Schema, owner: string): string {
    const ref = refName(s);
    if (ref) return py(ref);
    if (s.enum) return `Literal[${s.enum.map(py).join(", ")}]`;
    switch (s.type) {
      case "string":
        return "str";
      case "integer":
        return "int";
      case "number":
        return "float";
      case "boolean":
        return "bool";
      case "array":
        return `list[${typeOf(s.items ?? {}, owner + "Item")}]`;
      case "object": {
        if (Object.keys(s.properties ?? {}).length === 0) {
          return typeof s.additionalProperties === "object" ? `dict[str, ${typeOf(s.additionalProperties, owner + "Value")}]` : "dict[str, Any]";
        }
        typedDict(owner, s);
        return py(owner);
      }
    }
    return "Any";
  }
  function typedDict(name: string, s: Schema) {
    const required = new Set(s.required ?? []);
    const fields = Object.entries(s.properties ?? {}).map(([prop, p]) => {
      const t = typeOf(p, name + pascal(prop));
      return `    ${py(prop)}: ${required.has(prop) ? `Required[${t}]` : t},`;
    });
    blocks.push(docLine(s.description) + `${name} = TypedDict(${py(name)}, {\n${fields.join("\n")}\n}, total=False)\n`);
  }
  for (const [name, schema] of Object.entries(spec.components.schemas)) {
    if (schema.type === "object" && Object.keys(schema.properties ?? {}).length > 0) typedDict(name, schema);
    else blocks.push(docLine(schema.description) + `${name} = ${typeOf(schema, name)}\n`);
  }
  const methods: string[] = [];
  for (const [path, ops] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(ops)) {
      const pathParams = (op.parameters ?? []).filter((p) => p.in === "path").map((p) => p.name);
      const query = (op.parameters ?? []).filter((p) => p.in === "query");
      if (query.length > 0) {
        const props: Record<string, Schema> = {};
        for (const p of query) props[p.name] = p.schema;
        typedDict(`${pascal(op.operationId)}Query`, { type: "object", properties: props, required: query.filter((p) => p.required).map((p) => p.name) });
      }
      const body = refName(op.requestBody?.content?.["application/json"]?.schema);
      const ok = Object.keys(op.responses).filter((c) => c.startsWith("2")).sort()[0];
      const result = (ok && refName(op.responses[ok]?.content?.["application/json"]?.schema)) || "None";
      const args = ["self", ...pathParams.map((p) => `${p}: str`), ...(body ? [`body: ${body}`] : []), ...(query.length ? [`query: ${pascal(op.operationId)}Query | None = None`] : [])];
      const urlPath = pathParams.reduce((acc, p) => acc.replace(`{${p}}`, `" + _segment(${p}) + "`), py(path)).replace(/ \+ ""$/, "");
      methods.push(
        `    def ${snake(op.operationId)}(${args.join(", ")}) -> ${result}:\n` +
          `        """${method.toUpperCase()} ${path}"""\n` +
          `        return self._transport.request(${py(method.toUpperCase())}, ${urlPath}, ${body ? "body" : "None"}, ${query.length ? "query" : "None"})`,
      );
    }
  }
  return [
    "# Code generated by scripts/generate-python-sdk.ts from server/api/openapi.yaml. DO NOT EDIT.",
    `# ${spec.info.title} ${spec.info.version}.`,
    "from __future__ import annotations",
    "",
    "from typing import Any, Literal, Required, TypedDict",
    "",
    "from ._transport import KBClientOptions, Transport, _segment",
    "",
    ...blocks,
    "",
    "class KBClient:",
    '    """A typed client for kb\'s REST API. Each method is one operation in server/api/openapi.yaml."""',
    "",
    "    def __init__(self, origin: str, bearer: str, *, timeout: float = 30.0, max_response_bytes: int = 16 << 20) -> None:",
    "        self._transport = Transport(KBClientOptions(origin, bearer, timeout, max_response_bytes))",
    "",
    methods.join("\n\n"),
    "",
  ].join("\n");
}

export const PYTHON_OUTPUT_PATH = join(import.meta.dir, "..", "sdk", "python", "kb_client", "_generated.py");

if (import.meta.main) {
  // SAFETY: the contract is JSON-formatted OpenAPI 3.0; generatePython() reads only the fields typed above.
  const spec = JSON.parse(readFileSync(SPEC_PATH, "utf8")) as Spec;
  writeFileSync(PYTHON_OUTPUT_PATH, generatePython(spec));
}
