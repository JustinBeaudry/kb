#!/usr/bin/env bun
/**
 * Generates sdk/typescript/src/kb.ts, the typed TypeScript client, from
 * server/api/openapi.yaml (stored as JSON). Deterministic and
 * dependency-free; tests/sdk.test.ts fails when the committed output drifts.
 * The wire types are the same ones scripts/generate-memory-api.ts writes.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { generate, SPEC_PATH } from "./generate-memory-api";

type Ref = { $ref?: string };
type Parameter = { name: string; in: string; required?: boolean };
type Operation = {
  operationId: string;
  summary?: string;
  description?: string;
  parameters?: Parameter[];
  requestBody?: { content?: { "application/json"?: { schema?: Ref } } };
  responses: Record<string, { content?: { "application/json"?: { schema?: Ref } } }>;
};
type Spec = Parameters<typeof generate>[0] & { paths: Record<string, Record<string, Operation>> };

const refName = (r: Ref | undefined) => r?.$ref?.replace("#/components/schemas/", "");
const pascal = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const doc = (text: string) => `  /** ${text.replaceAll("*/", "* /").replace(/\s+/g, " ").trim()} */\n`;

export function generateClient(spec: Spec): string {
  const types = generate(spec).split("\n").slice(3).join("\n");
  const methods: string[] = [];
  for (const [path, ops] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(ops)) {
      const pathParams = (op.parameters ?? []).filter((p) => p.in === "path").map((p) => p.name);
      const hasQuery = (op.parameters ?? []).some((p) => p.in === "query");
      const bodyType = refName(op.requestBody?.content?.["application/json"]?.schema);
      const ok = Object.keys(op.responses).filter((c) => c.startsWith("2")).sort()[0];
      const resultType = (ok && refName(op.responses[ok]?.content?.["application/json"]?.schema)) || "void";
      const args = [
        ...pathParams.map((p) => `${p}: string`),
        ...(bodyType ? [`body: ${bodyType}`] : []),
        ...(hasQuery ? [`query?: ${pascal(op.operationId)}Query`] : []),
        "options?: RequestOptions",
      ];
      const urlPath = pathParams.reduce((acc, p) => acc.replace(`{${p}}`, `\${segment(${p})}`), path);
      const summary = op.summary ?? op.description ?? "";
      methods.push(
        doc(`${method.toUpperCase()} ${path}${summary ? `. ${summary}` : ""}`) +
          `  async ${op.operationId}(${args.join(", ")}): Promise<${resultType}> {\n` +
          `    return this.transport.request<${resultType}>(${JSON.stringify(method.toUpperCase())}, \`${urlPath}\`, ${bodyType ? "body" : "undefined"}, ${hasQuery ? "query" : "undefined"}, options);\n` +
          `  }`,
      );
    }
  }
  return [
    "// Code generated by scripts/generate-sdk.ts from server/api/openapi.yaml. DO NOT EDIT.",
    `// ${spec.info.title} ${spec.info.version}.`,
    "",
    'import { Transport, segment, type KBClientOptions, type RequestOptions } from "./runtime";',
    "",
    'export { KBError, canonicalOrigin, type KBClientOptions, type RequestOptions } from "./runtime";',
    "",
    types.trimEnd(),
    "",
    "/** A typed client for kb's REST API. Each method is one operation in server/api/openapi.yaml. */",
    "export class KBClient {",
    "  private readonly transport: Transport;",
    "",
    "  constructor(options: KBClientOptions) {",
    "    this.transport = new Transport(options);",
    "  }",
    "",
    methods.join("\n\n"),
    "}",
    "",
  ].join("\n");
}

export const SDK_OUTPUT_PATH = join(import.meta.dir, "..", "sdk", "typescript", "src", "kb.ts");

if (import.meta.main) {
  // SAFETY: the contract is JSON-formatted OpenAPI 3.0; generateClient() reads only the fields typed above.
  const spec = JSON.parse(readFileSync(SPEC_PATH, "utf8")) as Spec;
  writeFileSync(SDK_OUTPUT_PATH, generateClient(spec));
}
